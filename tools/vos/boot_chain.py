"""M3.5b's target chain campaign: its cases, its host oracle, its staged inputs and its join.

[The boot-handoff contract](../../docs/implementation/contracts/boot-handoff.md)'s section
9 is the predicate this module serves. It owns four things, each host Python that needs
neither the contained compiler nor the emulator:

1. **The case realization.** `CASES` states how each row of section 9.12's case table is
   realized, and `require_cases` holds the set against `boot_handoff.chain_cases`, the
   table's own parse, so a row the table gains or loses refuses every run.
2. **The host oracle** of section 9.2: from a case's inputs it computes, over `hashlib`'s
   SHAKE256 and independently of the firmware C, every byte that crosses a run boundary
   and every verdict, by sections 9.5 to 9.8: the state records, the capture head's
   compared fields, the handoff record, the placed M-mode window, the item-6 request and
   response, the M-mode capture and the main-die exit codes. A signature verdict is the
   one fact it does not compute: it is the campaign's disposable OpenSSL keys' verdict,
   recorded per exact (key, prefix, signature) at staging and looked up here.
3. **The staged inputs** (section 9.14): `staged` holds `firmware/chain/target/` to its
   manifest, to this checkout's sources and to section 9.13's identity freeze with
   M7.1f's staged manifest, as `boot_crypto_target.staged` holds the signature streams.
4. **The join** of shard receipts into one campaign receipt (F-718's identities).

Every constant is read from `firmware/chain/vos_chain.h` and `vos_boot.h` through
`boot_handoff.chain_layout`; the composition facts the oracle needs beside them (the
lifecycle state, the entropy root's source count, the watchdog's bounds) are read from
the shipped RoT configuration. Staging and execution live in `boot_chain_target`.

**What the contract leaves silent the oracle names rather than guesses.** Section 9.11
compares a refusal's capture head byte for byte but does not say whether a refusal
writes a digest, version or length it computed before refusing. For those fields alone
the comparison admits zero or the value the check reached and records which it saw
(`SILENT`); every other byte, gaps included, is compared exactly or, for the watchdog's
clock-dependent fields, by section 9.11's predicates.
"""

