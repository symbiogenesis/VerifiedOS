# --- the case realization -----------------------------------------------------------


@dataclass(frozen=True)
class Spec:
    """How one row of section 9.12's case table is realized.

    `run` is the table's run kind. A joined case's inputs are the boot-control values at
    power-on, the lifecycle state (None for the shipped one), the injected entropy
    failure, and which store image is altered and how; a main-die case alters the
    stage-2 image or the item-6 response over `cold-boot`'s R1 and R2; a runtime-only
    case names its runtime mutant and whether the external clock runs.
    """

    name: str
    run: str
    boot_target: int = 0
    slot: int = 0
    at_bound: bool = False
    lifecycle: str | None = None
    entropy_failed: bool = False
    stage0: str = "valid"
    slot_a: str = "valid"
    kernel: str = "valid"
    response: str = "bound"
    mutant: str | None = None
    clock: bool = True

    def ending(self) -> str:
        """A runtime-only case's required ending."""
        if self.mutant == "early-pet":
            return "bite-early"
        return "bite-late" if self.clock else "limit"

    def inputs(self) -> dict[str, object]:
        return {key: value for key, value in asdict(self).items() if key != "name"}


