def listing(root: Path, directory: str) -> list[str]:
    """Every file under one search directory by name, outside both staged trees."""
    base = root.resolve() / directory
    excluded = tuple((root.resolve() / tree).resolve()
                     for tree in (STAGED, boot_crypto_target.STAGED))
    return sorted(path.relative_to(base).as_posix() for path in base.rglob("*")
                  if path.is_file() and not any(path.resolve().is_relative_to(tree)
                                                for tree in excluded))


def freeze_findings(root: Path, manifest: Mapping[str, Any]) -> list[str]:
    """Section 9.13: the chain's verifier identities against M7.1f's staged manifest."""
    crypto = json.loads((root / boot_crypto_target.MANIFEST).read_text(encoding="utf-8"))
    found: list[str] = []
    sources = manifest.get("sources_sha256", {})
    crypto_sources = crypto.get("sources_sha256", {})
    for path in FROZEN:
        if path not in sources:
            found.append(f"no chain unit compiled {path}")
        elif sources[path] != crypto_sources.get(path):
            found.append(f"{path} as the chain compiled it is not {boot_crypto_target.MANIFEST}'s")
    chain_compiler = manifest.get("compiler_provenance", {})
    crypto_compiler = crypto.get("compiler_provenance", {})
    found += [f"the chain's compiler {key} is not {boot_crypto_target.MANIFEST}'s"
              for key in ("revision", "compiler_sha256")
              if not chain_compiler.get(key) or chain_compiler.get(key) != crypto_compiler.get(key)]
    ini = manifest.get("compiler_inputs_sha256", {}).get("compcert.ini")
    if ini is None or ini != crypto.get("compiler_inputs_sha256", {}).get("compcert.ini"):
        found.append(f"the chain's compcert.ini is not {boot_crypto_target.MANIFEST}'s")
    for unit, entry in manifest.get("units", {}).items():
        argv = entry.get("argv", []) if isinstance(entry, dict) else []
        missing = [argument for argument in REQUIRED_ARGUMENTS if argument not in argv]
        if missing:
            found.append(f"the {unit} unit was compiled without {', '.join(missing)}")
    return found


def _image_findings(f: Facts, name: str, data: bytes, entry: Mapping[str, Any]) -> list[str]:
    """One staged image against its manifest entry and its own header."""
    found: list[str] = []
    if hashlib.sha256(data).hexdigest() != entry.get("sha256"):
        found.append(f"{name} differs from its manifest")
    stage = entry.get("stage")
    kernel = stage == f["BOOT_STAGE_CORE_KERNELS"]
    size = f["CHAIN_KSTAGE_HEADER_BYTES"] if kernel else f["BOOT_HEADER_BYTES"]
    region = {f["BOOT_STAGE_ROT_RUNTIME"]: f["CHAIN_ROT_RUNTIME_REGION_BYTES"],
              f["BOOT_STAGE_MMODE_IMAGE"]: f["CHAIN_MMODE_REGION_BYTES"],
              f["BOOT_STAGE_CORE_KERNELS"]: f["CHAIN_KERNEL_REGION_BYTES"]}.get(cast("int", stage))
    if region is None or len(data) < size:
        return [*found, f"{name} is not a stage-0, -1 or -2 image"]
    magic = f["CHAIN_KSTAGE_MAGIC"] if kernel else f["BOOT_MAGIC"]
    length = _word(data, f["BOOT_HDR_PAYLOAD_LENGTH"])
    at = f["BOOT_HDR_PAYLOAD_DIGEST"]
    if (_word(data, f["BOOT_HDR_MAGIC"]) != magic or _word(data, f["BOOT_HDR_STAGE"]) != stage
            or _word(data, f["BOOT_HDR_PAYLOAD_OFFSET"]) != size or not 0 < length <= region
            or len(data) != size + length
            or data[at:at + f["BOOT_DIGEST_BYTES"]] != shake(f, data[size:])
            or _word(data, f["BOOT_HDR_SECURITY_VERSION"]) != entry.get("security_version")
            or length != entry.get("payload_length")):
        found.append(f"{name}'s header does not describe its payload and manifest entry")
    return found


@dataclass(frozen=True)
class Staged:
    """The staged directory, held to its manifest: streams, images and keys."""

    manifest: dict[str, Any]
    streams: dict[str, str]
    images: dict[str, bytes]
    roots: dict[int, bytes]
    kernel_root: bytes

    def inputs(self) -> Inputs:
        return Inputs(self.images, self.roots, self.kernel_root, recorded_verify(self.manifest))


def present(root: Path) -> bool:
    """Whether anything of the staged directory exists in this checkout."""
    directory = root / STAGED
    return directory.is_dir() and any(directory.iterdir())


def staged(root: Path) -> Staged:
    """The staged directory against its manifest, this checkout's sources, section 9.13's
    freeze and `boot-crypto verify`. No composer runs here; `boot_chain_target.layouts`
    re-derives the payloads where the composers are."""
    root = root.resolve()
    directory = root / STAGED
    if not directory.is_dir():
        raise ValueError(f"{STAGED} is not staged; run {GENERATOR}")
    present_files = sorted(path.name for path in directory.iterdir())
    if present_files != sorted(STAGED_FILES):
        raise ValueError(f"{STAGED} must hold exactly {sorted(STAGED_FILES)}, not {present_files}")
    manifest = json.loads((root / MANIFEST).read_text(encoding="utf-8"))
    if (not isinstance(manifest, dict) or manifest.get("schema") != 1
            or manifest.get("generator") != GENERATOR or manifest.get("contract") != bh.CONTRACT
            or not isinstance(manifest.get("floor"), int)):
        raise ValueError("the staged manifest does not describe this campaign")
    f = facts(root, cast("int", manifest["floor"]))
    files = manifest.get("files_sha256")
    if not isinstance(files, dict) or set(files) != set(STAGED_FILES) - {"manifest.json"}:
        raise ValueError("the staged manifest does not bind every staged file")
    for name, value in files.items():
        if receipts.digest(directory / name) != value:
            raise ValueError(f"{STAGED}/{name} differs from its manifest")
    sources = manifest.get("sources_sha256")
    if not isinstance(sources, dict) or not sources:
        raise ValueError("the staged manifest binds no source")
    for name, value in sources.items():
        path = (root / name).resolve()
        if not path.is_relative_to(root) or path.is_relative_to(directory):
            raise ValueError(f"invalid staged source: {name}")
        if not path.is_file() or receipts.digest(path) != value:
            raise ValueError(f"the staged chain is stale: {name} changed since staging; "
                             f"rerun {GENERATOR}")
    searched = manifest.get("search_directories")
    if (not isinstance(searched, dict)
            or not {PurePosixPath(name).parent.as_posix() for name in sources} <= set(searched)):
        raise ValueError("the staged manifest does not list every include search directory")
    for name, names in searched.items():
        path = (root / name).resolve()
        if not path.is_relative_to(root) or not path.is_dir():
            raise ValueError(f"invalid staged search directory: {name}")
        if listing(root, name) != names:
            raise ValueError(f"the staged chain is stale: the files in {name} changed since "
                             f"staging; rerun {GENERATOR}")
    units = manifest.get("units")
    if not isinstance(units, dict) or set(units) != set(UNITS):
        raise ValueError(f"the staged manifest must hold exactly the units {list(UNITS)}")
    header = HEADER.encode("utf-8")
    streams: dict[str, str] = {}
    for unit in UNITS:
        entry = units[unit]
        if not isinstance(entry, dict) or entry.get("file") != f"{unit}.s":
            raise ValueError(f"{unit} staged entry names another file")
        data = (directory / f"{unit}.s").read_bytes()
        if not data.startswith(header):
            raise ValueError(f"{unit} staged stream lacks its generated header")
        raw = data[len(header):]
        if hashlib.sha256(raw).hexdigest() != entry.get("assembly_sha256"):
            raise ValueError(f"{unit} staged stream differs from its manifest")
        stream = raw.decode("utf-8")
        if cd.refusals(stream):
            raise ValueError(f"{unit} staged stream is outside the accepted dialect")
        streams[unit] = stream
    stored = json.loads((root / IMAGES).read_text(encoding="utf-8"))
    entries = manifest.get("images")
    if (not isinstance(stored, dict) or stored.get("schema") != 1
            or not isinstance(stored.get("images"), dict) or not isinstance(entries, dict)
            or set(stored["images"]) != set(IMAGE_NAMES) or set(entries) != set(IMAGE_NAMES)):
        raise ValueError(f"{IMAGES} and the manifest must hold exactly {list(IMAGE_NAMES)}")
    images = {name: bytes.fromhex(cast("str", stored["images"][name])) for name in IMAGE_NAMES}
    problems = [problem for name in IMAGE_NAMES
                for problem in _image_findings(f, name, images[name], entries[name])]
    keys = manifest.get("keys", {})
    rom_roots = keys.get("rom_roots", {}) if isinstance(keys, dict) else {}
    if not isinstance(rom_roots, dict) or set(rom_roots) != set(bh.ROOT_STATES):
        raise ValueError(f"the staged manifest must carry one ROM root for each of {bh.ROOT_STATES}")
    roots = {bh.LIFECYCLES.index(state): bytes.fromhex(value) for state, value in rom_roots.items()}
    kernel_root = bytes.fromhex(cast("str", keys.get("kernel_root", "")))
    if any(len(key) != f["BOOT_PUBLIC_KEY_BYTES"] for key in roots.values()):
        problems.append("a ROM root is not an SLH-DSA-SHAKE-256s public key")
    if len(kernel_root) != f["CHAIN_KSTAGE_PUBLIC_KEY_BYTES"]:
        problems.append("the kernel-stage root is not an ML-DSA-87 public key")
    header_bytes = f["BOOT_HEADER_BYTES"]
    for name, tag in (("mmode-a", f.tags[0]), ("mmode-b", f.tags[1]),
                      ("mmode-recovery", f.tags[2]), ("mmode-a-below-floor", f.tags[0])):
        payload = images[name][header_bytes:]
        if not payload.endswith(tag) or kernel_root not in payload:
            problems.append(f"{name}'s payload does not carry the kernel-stage root and its tag")
    if images["mmode-a-below-floor"][header_bytes:] != images["mmode-a"][header_bytes:]:
        problems.append("the below-floor image does not carry slot A's payload")
    verify = recorded_verify(manifest)
    production = roots.get(f.lifecycle)
    try:
        for name in IMAGE_NAMES:
            image, kernel = images[name], name == "kernel"
            key = kernel_root if kernel else production
            if key is None or not verify(MLDSA if kernel else SLH, key,
                                         image[:f["BOOT_SIGNED_BYTES"]],
                                         image[f["BOOT_HDR_SIGNATURE"]:(f["CHAIN_KSTAGE_HEADER_BYTES"]
                                               if kernel else header_bytes)]):
                problems.append(f"OpenSSL did not accept {name} under its root")
    except ValueError as exc:
        problems.append(str(exc))
    problems += freeze_findings(root, manifest)
    if problems:
        raise ValueError("; ".join(problems))
    boot_crypto_target.staged(root)
    return Staged(manifest, streams, images, roots, kernel_root)


