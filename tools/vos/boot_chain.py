# Every shard of one joined campaign must agree on these (F-718's identities).
SHARED = ("source_sha256", "model_source_sha256", "staged_manifest_sha256", "compiler_provenance",
          "compiler_inputs_sha256", "freeze", "periods_ns", "inst_limits", "timeouts", "floor",
          "watchdog_bounds", "contract", "scope")


def join(root: Path, reports: Mapping[str, Any], digests: Mapping[str, str]) -> dict[str, Any]:
    """One campaign receipt from shard receipts of the same inputs.

    The case set is section 9.12's table exactly; each case comes from at most one
    shard, every shared identity agrees, a main-die shard's `cold-boot` inputs are the
    ones `cold-boot`'s own shard recorded, and a case no shard executed is listed. The
    campaign passes only when every case executed and passed, `cold-boot` first.
    """
    universe = [row.name for row in require_cases(root)]
    if not reports:
        raise ValueError("a joined campaign needs shard reports")
    reference = next(iter(reports.values()))
    owners: dict[str, str] = {}
    rows: dict[str, dict[str, Any]] = {}
    shards: dict[str, object] = {}
    for name, report in reports.items():
        if isinstance(report, dict) and "error" in report:
            raise ValueError(f"{name} stopped before its cases completed: {report['error']}")
        if not isinstance(report, dict) or report.get("status") not in ("passed", "failed"):
            raise ValueError(f"{name} is not a completed chain report")
        for key in SHARED:
            if report.get(key) != reference.get(key):
                raise ValueError(f"{name} differs from the other shards in {key}")
        selection, cases = report.get("selection"), report.get("cases")
        if (not isinstance(selection, list) or not selection or not isinstance(cases, list)
                or not all(isinstance(row, dict) for row in cases)):
            raise ValueError(f"{name} lacks its selection or cases")
        for case in selection:
            if case not in universe:
                raise ValueError(f"{name} selects {case}, which section 9.12 does not name")
            if case in owners:
                raise ValueError(f"{name} repeats {case}, which {owners[case]} selected")
            owners[case] = name
        executed = [row.get("case") for row in cases]
        if len(set(executed)) != len(executed) or not set(executed) <= set(selection):
            raise ValueError(f"{name} executed a case twice or outside its selection")
        if report.get("unexecuted_cases") != [case for case in selection if case not in executed]:
            raise ValueError(f"{name} misstates its unexecuted cases")
        if report.get("passed") is not (len(executed) == len(selection)
                                        and all(row.get("passed") is True for row in cases)):
            raise ValueError(f"{name} states a verdict its cases do not support")
        for row in cases:
            rows[str(row["case"])] = {**row, "shard": name}
        shards[name] = {key: report.get(key) for key in (
            "selection", "status", "seconds", "jobs", "inputs_sha256", "cold_boot")}
    cold = rows.get(COLD_BOOT)
    for name, report in reports.items():
        imported = report.get("cold_boot")
        if imported is None:
            continue
        if not isinstance(imported, dict):
            raise TypeError(f"{name} records its cold-boot inputs in no readable form")
        if cold is None:
            raise ValueError(f"{name} ran main-die cases over a cold-boot no shard reports")
        if (imported.get("report_sha256") != digests.get(cold["shard"])
                or imported.get("r1_capture_sha256") != cold.get("r1_capture_sha256")
                or imported.get("r2_response_sha256") != cold.get("r2_response_sha256")):
            raise ValueError(f"{name}'s cold-boot inputs are not the ones cold-boot's receipt records")
    ordered = [rows[case] for case in universe if case in rows]
    unexecuted = [case for case in universe if case not in rows]
    cold_passed = cold is not None and cold.get("passed") is True
    passed = cold_passed and not unexecuted and all(row.get("passed") is True for row in ordered)
    return {"passed": passed, "status": "passed" if passed else "failed", "cases": ordered,
            "case_set": universe, "unexecuted_cases": unexecuted, "cold_boot_passed": cold_passed,
            **{key: reference.get(key) for key in SHARED}, "shards": shards,
            "shard_reports_sha256": dict(digests), "milestone_acceptance": "open"}


def configuration_variant(root: Path, base: str, changes: Mapping[tuple[str, ...], object],
                          path: Path) -> dict[str, object]:
    """A copy of a shipped configuration with only `changes` made, written to `path`.

    Every changed key must already be declared, and the variant's every other leaf must
    be the shipped file's; the record names the base, both digests and the changes.
    """
    shipped = jsonc.load(root / base)
    variant = json.loads(json.dumps(shipped))
    for keys, value in changes.items():
        node = _walk(variant, *keys[:-1])
        if not isinstance(node, dict) or keys[-1] not in node:
            raise ValueError(f"{base} declares no {'.'.join(keys)}; the variant would add it")
        cast("dict[str, object]", node)[keys[-1]] = value
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(variant, indent=2) + "\n", encoding="utf-8", newline="\n")
    before, after = config.flat(shipped), config.flat(jsonc.load(path))
    changed = {key for key in before.keys() | after.keys() if before.get(key) != after.get(key)}
    if not changed <= {".".join(keys) for keys in changes}:
        raise ValueError(f"the variant of {base} changes {sorted(changed)} beyond its keys")
    return {"base": base, "base_sha256": receipts.digest(root / base), "file": path.name,
            "sha256": receipts.digest(path),
            "changes": {".".join(keys): value for keys, value in changes.items()}}
