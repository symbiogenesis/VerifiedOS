"""M1.2f's two loops driven end to end with no backend and no toolchain.

The compiler, the emulator and the Wasm host are each a script written here: one
`ccomp` emits a stream in the frozen dialect, one emits the lp64d stream stock CompCert
writes, and one refuses; the emulator prints the HTIF line and the commit records the
real one prints and writes the terminal log; the Wasm host prints one boolean. What the
cases decide is the driver's own behaviour over those: that a refused stream is reported
by mnemonic, directive and line, that a dialect stream is assembled under the harness and
run, that the two questions are read back as the corpus reads them, that the recorded-run
comparator names the first disagreement, and that the declared component encoding round
trips and its comparator names the first field. The real compiler, the lane's emulator
and the oracle's switch are exercised by hand and quoted in the completion note.
"""

