# A stream in the frozen dialect, in the shape CompCert's printer writes: a tab between
# the mnemonic and its operands, local labels, and the function-info trailer.
DIALECT: Final = """\
# Emitted by a fake ccomp: a stream in the frozen dialect, in CompCert's printer's shape.
\t.text
\t.balign 4
\t.globl\tmain
main:
\tcincoffsetimm\tcsp, csp, -16
\tsc\tcra, 8(csp)
\tli\ta5, 41
\taddi\ta0, a5, 1
\tli\ta4, 42
\tbne\ta0, a4, .L100
\tli\ta0, 0
\tj\t.L101
.L100:
\tli\ta0, 1
.L101:
\tlc\tcra, 8(csp)
\tcincoffsetimm\tcsp, csp, 16
\tret
\t.type\tmain, @function
\t.size\tmain, . - main
"""

# The lp64d stream stock `ccomp -S` writes for the same kind of program: integer-relative
# addressing, `jr`, `sext.w`, and the data directives CompCert spells.
LP64D: Final = """\
# File generated by CompCert 3.17
# Command line: -S g1-00-pointer.c
\t.option nopic
\t.text
\t.balign 2
\t.globl\tmain
main:
\taddi\tsp, sp, -16
\tsd\tra, 8(sp)
\tla\ta5, cells
\tli\ta4, 41
\tsw\ta4, 4(a5)
\tlw\ta4, 4(a5)
\tsext.w\ta4, a4
\tli\ta3, 41
\tbne\ta4, a3, .L100
\tli\ta0, 0
\tj\t.L101
.L100:
\tli\ta0, 1
.L101:
\tld\tra, 8(sp)
\taddi\tsp, sp, 16
\tjr\tra
\t.type\tmain, @function
\t.size\tmain, . - main
\t.local\tcells
\t.comm\tcells, 16, 8
\t.data
\t.balign 8
\t.globl\ttable
table:
\t.quad\tcells
\t.long\t7
\t.short\t3
\t.byte\t1
"""

# What the scan owes over LP64D: each refused head, by kind, found at the line carrying it.
REFUSED: Final = (("directive", ".option"), ("mnemonic", "sext.w"), ("mnemonic", "jr"),
                  ("directive", ".local"), ("directive", ".comm"), ("directive", ".quad"),
                  ("directive", ".long"), ("directive", ".short"))

DIALECT_C: Final = "/* FAKE-CCOMP: dialect */\nint main(void) { return 0; }\n"
LP64D_C: Final = "int main(void) { return 0; }\n"
REFUSING_C: Final = "/* FAKE-CCOMP: refuse */\nint main(void) { return 0; }\n"

# The commit records the fake emulator prints: a tagged write read back tagged at the same
# address, which is the third reading the driver reports beside the digest.
RECORDS: Final = ("I 1 0000000080000000 0002E403", "X 8 1 0000000080000000",
                  "I 2 0000000080000004 00000013", "W 0000000080008010 8 1 000000008000C000",
                  "I 3 0000000080000008 00000013", "R 0000000080008010 8 1 000000008000C000")

FAKE_CCOMP: Final = f"""\
import pathlib, sys
args = sys.argv[1:]
source = pathlib.Path(next(a for a in args if a.endswith(".c")))
out = pathlib.Path(args[args.index("-o") + 1])
text = source.read_text(encoding="utf-8")
if "FAKE-CCOMP: refuse" in text:
    sys.stderr.write("fake ccomp: refused on purpose\\n")
    sys.exit(2)
stream = {DIALECT!r} if "FAKE-CCOMP: dialect" in text else {LP64D!r}
out.write_text(stream, encoding="utf-8", newline="")
"""

FAKE_SIM: Final = f"""\
import pathlib, sys
args = sys.argv[1:]
elf = pathlib.Path(args[-1])
pathlib.Path(args[args.index("--terminal-log") + 1]).write_bytes(b"true\\n")
name = elf.stem
print("HTIF located at 0x80008000")
for record in {RECORDS!r}:
    print(record)
if "fail2" in name:
    print("FAILURE: 2 (0x00000002)")
elif "trap" in name:
    print("FAILURE: 284 (0x0000011c)")
elif "loop" in name:
    print("FAILURE: possible trap loop detected with MEPC=0x80000010")
elif "silent" not in name:
    print("SUCCESS")
"""

# Bytes rather than `print`, because the real host is Node on Linux and writes `\\n`, where
# a Windows interpreter's text-mode stdout would write `\\r\\n` and the encoding is exact.
FAKE_NODE: Final = """\
import sys
module = sys.argv[-1]
if "seeded" in module:
    sys.stdout.buffer.write(b"false\\n")
    sys.exit(1)
sys.stdout.buffer.write(b"true\\n")
"""


def _script(directory: Path, name: str, text: str) -> Path:
    path = directory / f"{name}.py"
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


def _wrapper(directory: Path, name: str, script: Path) -> Path:
    """The script as an executable a `--ccomp` or `--simulator` flag can name."""
    if sys.platform == "win32":
        path = directory / f"{name}.cmd"
        path.write_text(f'@"{sys.executable}" "{script}" %*\r\n', encoding="utf-8",
                        newline="")
        return path
    path = directory / name
    path.write_text(f'#!/bin/sh\nexec "{sys.executable}" "{script}" "$@"\n',
                    encoding="utf-8", newline="")
    path.chmod(0o755)
    return path


def _lines_of(stream: str, head: str) -> list[int]:
    return [n for n, raw in enumerate(stream.splitlines(), 1)
            if raw.replace("\t", " ").strip().split(" ")[0] == head]


def _generator_is_deterministic() -> None:
    first, second = cd.programs(7, 6), cd.programs(7, 6)
    ensure(first == second, "one seed and count must name one campaign")
    ensure(len({p.name for p in first}) == 6, "every program needs a name of its own")
    ensure([p.pattern for p in first] == ["pointer", "struct", "call"] * 2,
           f"the patterns cycle, got {[p.pattern for p in first]}")
    for program in first:
        ensure("int main(void)" in program.source and program.checks > 0,
               f"{program.name} must define main and carry checks")
        ensure("double" not in program.source and "float" not in program.source,
               f"{program.name} must be FP-free (R-15-039)")
    ensure(cd.programs(8, 6) != first, "a different seed draws different constants")


def _scan_names_what_the_dialect_refuses() -> None:
    found = {(r.kind, r.name, r.line) for r in cd.refusals(LP64D)}
    wanted = {(kind, name, line) for kind, name in REFUSED
              for line in _lines_of(LP64D, name)}
    ensure(found == wanted, f"the scan must name exactly the refused heads by line:\n"
                            f"found  {sorted(found)}\nwanted {sorted(wanted)}")
    ensure(cd.refusals(DIALECT) == [], "a dialect stream carries nothing to refuse")
    ensure(cd.refusals("\taddi\tsp, sp, -16\n") == [],
           "a tab between mnemonic and operands is normalized, not refused")
    ensure(cd.refusals("\t.section\t.rodata,\"a\",@progbits\n")
           == [cd.Refusal("section", ".rodata", 1)],
           "a section the image lacks is named by the section")
    ensure(cd.refusals("\t.space\n") == [cd.Refusal("operand", ".space", 1,
                                                    ".space takes a size")],
           "a known directive with a refused operand carries the parser's words")


def _harness_assembles_a_dialect_stream() -> None:
    with tempfile.TemporaryDirectory(prefix="vos-test-") as td:
        scratch = Path(td)
        once, twice = scratch / "a.elf", scratch / "b.elf"
        found, size = cd.assemble(DIALECT, "dialect", once)
        ensure(found == [] and size > cd.STACK_BYTES and once.is_file(),
               f"the dialect stream must assemble under the harness, got {found} {size}")
        cd.assemble(DIALECT, "dialect", twice)
        ensure(once.read_bytes() == twice.read_bytes(), "the image must be reproducible")
        composite = cd.compose(DIALECT).splitlines()
        ensure(composite[cd.STREAM_OFFSET] == DIALECT.splitlines()[0],
               "the stream's first line sits at STREAM_OFFSET in the composite")
        ensure(composite[0].startswith("#") and "_start:" in composite
               and "tohost:" in composite, "the harness declares _start and tohost")

        found, _ = cd.assemble("\t.text\n\tret\n", "nomain", scratch / "c.elf")
        ensure([r.kind for r in found] == ["symbol"] and found[0].name == "main",
               f"a stream without main is refused by symbol, got {found}")
        found, _ = cd.assemble("main:\n\tsd\tra, 8(sp), 1\n\tret\n", "bad", scratch / "d.elf")
        ensure(found == [cd.Refusal("operand", "sd", 2, "sd takes 2 operands, given 3")],
               f"an operand the layout refuses is named by the stream's line, got {found}")
        ensure(not (scratch / "d.elf").exists(), "no image is written for a refused stream")


def _loop_over_fake_ccomp_dialect() -> None:
    with tempfile.TemporaryDirectory(prefix="vos-test-") as td:
        scratch = Path(td)
        ccomp = [sys.executable, str(_script(scratch, "ccomp", FAKE_CCOMP))]
        sim = [sys.executable, str(_script(scratch, "sim", FAKE_SIM))]
        work = scratch / "work"
        work.mkdir()
        profile = scratch / "profile.json"
        run = cd.run_program(cd.Program("d-pass", "given", DIALECT_C, 1), ccomp, work,
                             sim, profile, "")
        ran = run.ran
        if ran is None:
            raise AssertionError(f"a dialect stream must reach the emulator, got "
                                 f"{run.verdict}: {run.detail}")
        ensure(run.verdict == "pass" and ran.code == 0,
               f"a dialect stream runs to a pass, got {run.verdict}: {run.detail}")
        expected = trace.normalize_commit(list(RECORDS))
        ensure(ran.records == len(expected) and ran.digest == trace.digest(expected),
               "the trace is normalized and digested as the corpus digests a member")
        ensure(ran.cap_roundtrip and ran.emitted == b"true\n",
               "a tagged write read back tagged is reported, and the terminal log is read")
        ensure(run.compiled is not None
               and run.compiled.argv == (*ccomp, "-S", "d-pass.c", "-o", "d-pass.s"),
               f"ccomp is asked with names relative to the fresh directory: "
               f"{run.compiled and run.compiled.argv}")
        ensure(sorted(p.name for p in (work / "d-pass").iterdir()) == ["d-pass.c", "d-pass.s"],
               "the fresh directory holds the source and the stream and nothing else")
        ensure(run.image_bytes > cd.STACK_BYTES and (work / "d-pass.elf").is_file(),
               "the image is written beside the stream")

        for name, verdict, code, said in (("d-fail2", "fail", 2, "main returned 2"),
                                          ("d-trap", "trap", 284, "cause 28"),
                                          ("d-silent", "no-verdict", None, "no HTIF verdict"),
                                          ("d-loop", "no-verdict", None, "trap loop")):
            run = cd.run_program(cd.Program(name, "given", DIALECT_C, 1), ccomp, work, sim,
                                 profile, "")
            ensure(run.verdict == verdict and run.ran is not None and run.ran.code == code
                   and said in run.detail,
                   f"{name}: wanted {verdict} {code} {said!r}, got {run.verdict} "
                   f"{run.ran and run.ran.code} {run.detail!r}")

        run = cd.run_program(cd.Program("d-wait", "given", DIALECT_C, 1), ccomp, work,
                             None, profile, "the emulator half waits")
        ensure(run.verdict == "assembled" and "waits" in run.detail and run.ran is None,
               f"with no emulator the image is assembled and the wait is said: {run}")


